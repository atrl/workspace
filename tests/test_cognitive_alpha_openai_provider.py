from __future__ import annotations

import json
import subprocess
import sys
import threading
from http.server import BaseHTTPRequestHandler, HTTPServer

import numpy as np
import pandas as pd


def _evolution_frame(rows: int = 120) -> pd.DataFrame:
    dates = pd.date_range("2024-01-02", periods=rows, freq="B")
    trend = np.linspace(0.0, 1.0, rows)
    cycle = np.sin(np.arange(rows) / 4.0)
    close = 30.0 + trend * 10.0 + cycle
    frame = pd.DataFrame(
        {
            "datetime": dates,
            "open": close * (1.0 - 0.002),
            "high": close * 1.02,
            "low": close * 0.98,
            "close": close,
            "volume": 1_000_000 + np.arange(rows) * 10_000 + cycle * 15_000,
        }
    )
    frame["label_return_5d"] = pd.Series(close).pct_change(5).shift(-5).ffill().fillna(0.0)
    return frame


def _read_jsonl(path):
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


class _ResponsesHandler(BaseHTTPRequestHandler):
    requests: list[dict] = []

    def do_POST(self):  # noqa: N802 - stdlib handler API
        length = int(self.headers.get("Content-Length", "0"))
        payload = json.loads(self.rfile.read(length).decode("utf-8"))
        self.__class__.requests.append(
            {
                "path": self.path,
                "authorization": self.headers.get("Authorization"),
                "payload": payload,
            }
        )
        body = {
            "id": "resp_unit",
            "output": [
                {
                    "content": [
                        {
                            "type": "output_text",
                            "text": json.dumps(
                                {
                                    "candidates": [
                                        {
                                            "name": "openai_generated_alpha_000",
                                            "level": "market_structure_cycle",
                                            "agent": "AgentMarketCycle",
                                            "theme": "trend continuation code alpha",
                                            "required_columns": ["close", "volume"],
                                            "lookback": 10,
                                            "code": "close.pct_change(5).shift(1)",
                                            "economic_rationale": "Lagged trend persistence generated by LLM.",
                                        }
                                    ]
                                }
                            ),
                        }
                    ]
                }
            ],
        }
        encoded = json.dumps(body).encode("utf-8")
        self.send_response(200)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(encoded)))
        self.end_headers()
        self.wfile.write(encoded)

    def log_message(self, *_args):
        return


def _start_responses_server():
    _ResponsesHandler.requests = []
    server = HTTPServer(("127.0.0.1", 0), _ResponsesHandler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server


def test_openai_responses_completion_posts_structured_prompt_and_extracts_candidates():
    from src.workflow.cognitive_alpha_openai_provider import openai_responses_completion

    server = _start_responses_server()
    try:
        request = {
            "paper_reference": "arxiv:2511.18850",
            "model": "unit-request-model",
            "request_index": 0,
            "target_candidate_count": 1,
            "level": "market_structure_cycle",
            "agent": "AgentMarketCycle",
            "theme": "large-scale trend",
            "guidance_style": "trend_continuation",
            "available_columns": ["close", "volume"],
            "alpha158_columns": ["alpha158_good"],
        }

        result = openai_responses_completion(
            request,
            api_key="unit-key",
            model="unit-model",
            base_url=f"http://127.0.0.1:{server.server_port}/v1/responses",
            timeout_seconds=5,
        )

        assert result["candidates"][0]["name"] == "openai_generated_alpha_000"
        posted = _ResponsesHandler.requests[0]
        assert posted["path"] == "/v1/responses"
        assert posted["authorization"] == "Bearer unit-key"
        assert posted["payload"]["model"] == "unit-model"
        assert posted["payload"]["text"]["format"]["type"] == "json_schema"
        assert posted["payload"]["text"]["format"]["name"] == "cognitive_alpha_candidates"
        input_text = json.dumps(posted["payload"]["input"], sort_keys=True)
        assert "arxiv:2511.18850" in input_text
        assert "AgentMarketCycle" in input_text
        assert "alpha158_good" in input_text
    finally:
        server.shutdown()


