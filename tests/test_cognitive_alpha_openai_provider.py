def test_openai_provider_cli_can_back_command_provider_with_external_process(tmp_path, monkeypatch):
    from src.workflow import (
        CognitiveAlphaEvolutionSpec,
        build_cognitive_alpha_command_llm_candidate_provider,
        run_cognitive_alpha_evolution,
    )

    server = _start_responses_server()
    try:
        provider = build_cognitive_alpha_command_llm_candidate_provider(
            command=(
                sys.executable,
                "-m",
                "src.workflow.cognitive_alpha_openai_provider",
                "--base-url",
                f"http://127.0.0.1:{server.server_port}/v1/responses",
                "--model",
                "unit-model",
            ),
            provider_id="unit_openai_responses",
            model="unit-model",
        )
        spec = CognitiveAlphaEvolutionSpec(
            run_id="openai_command_provider",
            profile="soxl_smoke",
            runtime_dir=tmp_path,
            generations=1,
            initial_pool_size=1,
            parent_pool_size=1,
            children_per_generation=1,
            qualified_percentile=0.50,
            elite_percentile=0.75,
            fallback_top_n=1,
        )
        monkeypatch.setenv("OPENAI_API_KEY", "unit-key")

        result = run_cognitive_alpha_evolution(
            _evolution_frame(rows=120),
            spec=spec,
            label_col="label_return_5d",
            candidate_provider=provider,
        )

        generation_zero = _read_jsonl(tmp_path / "openai_command_provider" / "candidate_pool" / "generation_000.jsonl")
        assert generation_zero[0]["metadata"]["provider_id"] == "unit_openai_responses"
        assert result.summary["candidate_provider"]["provider_kind"] == "external_llm_code"
    finally:
        server.shutdown()
