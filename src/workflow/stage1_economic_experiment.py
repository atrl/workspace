    summary["allocation_source"] = inputs["allocation_source"]
    shadow_models = {}
    for name, cutoff in (("own_state_frozen_2022", 2022), ("own_state_expanding_2025", 2025)):
        trained_model = trained[cutoff]
        diagnostic = trained_model["diagnostics"].loc[lambda x: x.model_year.eq(trained_model["final_model_year"])].iloc[-1]
        shadow_models[name] = {"policy": "net_value", "available": trained_model["final_model"] is not None,
            "artifact": f"artifacts/models/{name}.pkl", "sha256": summary["model_artifacts"][name]["sha256"],
            "training_signal_end": diagnostic.training_signal_end, "label_available_at_max": diagnostic.label_available_at_max,
            "test_decision_at": diagnostic.first_test_decision_at, "information_cutoff_exclusive": diagnostic.information_cutoff_exclusive}
    old_fit = inputs["legacy_diagnostics"].iloc[-1]
    shadow_models["rules_only"] = {"policy": "rules_only", "available": True, "artifact": "artifacts/models/rules_only_classifier.pkl",
        "sha256": summary["model_artifacts"]["rules_only"]["sha256"], "training_signal_end": old_fit.training_end,
        "label_available_at_max": old_fit.label_available_at_max, "test_decision_at": old_fit.test_decision_at}
    summary["shadow_models"] = shadow_models
    _json(card / "summary.json", summary)
    lines = ["# 调仓优化实验结论", "", "完成规则拆分、自身持仓路径净收益监督及动作模型扩展至2025年的对照。基础分配模型和恢复模型保持固定，以隔离动作层变化；不宣称完成基础分配器的数据年代更新。", "", "下表开发期为2016–2022年度walk-forward，10bp净费：", ""]
    for row in comparison[(comparison.segment == "development_walk_forward") & (comparison.cost_bps == 10)].itertuples():
        lines.append(f"- {row.variant}：收益{row.return_pct:.2f}%，MaxDD {row.max_drawdown_pct:.2f}%，CVaR5 {row.cvar5_pct:.2f}%，调仓{row.open_trade_days}日，换手{row.total_turnover:.3f}。")
    lines += ["", "门禁逐项记录于development_gates.csv；25bp按各自控制器重新走路径，不只从固定交易上扣费。", "", "原8/3起点短窗仅作事后诊断，不选参："]
    for row in origin_metrics[origin_metrics.cost_bps == 10].itertuples():
        lines.append(f"- {row.variant}：截至9/25收盘收益{row.return_pct:.2f}%，调仓{row.open_trade_days}日。")
    lines += ["", "自身状态训练使用年度决策前已成熟标签；共同次日目标复位成本仍是单会话代理，未训练新的长期恢复优化器。连续权重回放不等于整数股成交。", "", "所有新候选保持未晋升，只允许独立只读前向shadow收集证据；失败结果不替换active SIM，不复用旧失败授权收据。", f"QLib recorder：{recorder.id}。"]
    (card / "conclusion.md").write_text("\n".join(lines) + "\n")
    import yaml
    (card / "workflow.yaml").write_text(yaml.safe_dump({"experiment": EXPERIMENT, "provider_uri": "data/qlib/soxl_soxx_soxs", "region": "us", "recorder_uri": str(uri), "selection_plan": "selection_plan.json", "retained_inputs": "retained_inputs.json", "segments": {"development": ["2016-01-01", "2022-12-31"], "reused_diagnostic": ["2023-01-01", "2026-09-25"]}, "model_selection": "fixed bounded comparisons; no parameter search", "artifact_policy": summary["artifact_policy"]}, sort_keys=False))
    return summary
