"""Explicit information-mask aliases over the immutable native parent inputs.

Scalers retain their original variant names and hashes. Owned holdings are
generated by the policy's chronological rollout, never added to this Dataset.
"""
from __future__ import annotations

from copy import deepcopy
import hashlib
import json

import numpy as np

from src.data.benchmark_anchor_utility import transform_features
from src.data.constrained_net_excess import load_constrained_inputs
from src.workflow.benchmark_anchor_utility import prepare_folds as prepare_parent_folds
from src.workflow.anchor_checkpoint_feasibility import _same_evidence


VARIANT_MAPPING = {
    "holdings_only": "constant",
    "price_holdings": "price",
    "price_vol_holdings": "price_vol",
}
ENABLED_MARKET_FEATURES = {"holdings_only": 0, "price_holdings": 25, "price_vol_holdings": 27}


def variant_mapping(plan):
    variants = plan["variants"]
    names = [row["name"] for row in variants]
    if len(names) != len(set(names)) or set(names) != set(VARIANT_MAPPING):
        raise ValueError("blocked: sparse information families differ from registration")
    mapping = {row["name"]: row["parent_market_variant"] for row in variants}
    if mapping != VARIANT_MAPPING or plan["inputs"]["variant_mapping"] != mapping:
        raise ValueError("blocked: sparse-to-parent information masks differ")
    if any(row["enabled_market_features"] != ENABLED_MARKET_FEATURES[row["name"]] for row in variants):
        raise ValueError("blocked: sparse enabled market channels differ")
    return mapping


def parent_preparation_plan(plan):
    """Copy only: never rewrite the registered plan or old scaler identities."""
    mapping = variant_mapping(plan)
    parent = deepcopy(plan)
    parent["variants"] = [{**row, "name": mapping[row["name"]]} for row in plan["variants"]]
    return parent


def transform_for_variant(rows, scaler, *, variant, plan):
    mapping = variant_mapping(plan)
    if variant not in mapping or scaler.get("variant") != mapping[variant]:
        raise ValueError("blocked: sparse bundle points to a different parent scaler mask")
    return transform_features(rows, scaler, variant=mapping[variant])


def prepare_folds(dataset, variants, years, plan, *, parent_dev_folds=None):
    """Native mature rows plus unchanged old scalers, explicitly aliased."""
    mapping = variant_mapping(plan)
    if not variants or len(variants) != len(set(variants)) or any(v not in mapping for v in variants):
        raise ValueError("blocked: invalid sparse fold family inventory")
    prepared = prepare_parent_folds(dataset, [mapping[v] for v in variants], years,
                                    parent_preparation_plan(plan))
    folds = {}
    for name in variants:
        for year in years:
            original = prepared[(mapping[name], year)]
            if parent_dev_folds is not None:
                identity = (mapping[name], int(year))
                if identity not in parent_dev_folds:
                    raise ValueError("blocked: missing frozen parent development fold")
                previous = parent_dev_folds[identity]
                for field in ("scaler", "audit", "transform_audit", "invalid_training_dates"):
                    if not _same_evidence(original[field], previous[field]):
                        raise ValueError(f"blocked: sparse preparation changed parent {field}")
                if (not original["rows"].equals(previous["rows"])
                        or not np.array_equal(original["features"], previous["features"])
                        or not np.array_equal(original["returns"], previous["returns"])
                        or original["invalid_training"] != previous["invalid_training"]):
                    raise ValueError("blocked: sparse preparation changed parent rows or matrices")
            # Own the bundle containers; do not mutate the frozen source object.
            fold = deepcopy(original)
            fold["variant"] = name
            fold["parent_market_variant"] = mapping[name]
            folds[(name, int(year))] = fold
    return folds


def load_sparse_inputs(root, plan):
    """Read the original frozen Recorder and verify all 21 development folds."""
    mapping = variant_mapping(plan)
    bundle = load_constrained_inputs(root, parent_preparation_plan(plan))
    folds = prepare_folds(bundle["dataset"], list(mapping), plan["training"]["development_signal_years"],
                          plan, parent_dev_folds=bundle["parent_dev_folds"])
    bindings = [{"variant": name, "parent_market_variant": mapping[name], "model_year": year,
                 "scaler_sha256": fold["scaler"]["scaler_sha256"],
                 "eligible_dates_sha256": fold["audit"]["eligible_dates_sha256"],
                 "features_sha256": hashlib.sha256(fold["features"].astype(np.float64).tobytes()).hexdigest(),
                 "returns_sha256": hashlib.sha256(fold["returns"].astype(np.float64).tobytes()).hexdigest()}
                for (name, year), fold in folds.items()]
    details = {"frozen_parent": bundle["source_details"], "variant_bindings": bindings,
               "holdings_columns_stored_in_dataset": False}
    audit = {**bundle["source_audit"], "parent_market_variant_mapping": mapping,
             "mapped_development_folds": len(folds), "parent_scalers_modified": False,
             "holdings_generated_by_owned_policy_only": True,
             "details_sha256": hashlib.sha256(json.dumps(details, sort_keys=True, separators=(",", ":"),
                                                        allow_nan=False).encode()).hexdigest()}
    return {**bundle, "development_folds": folds, "variant_mapping": mapping,
            "source_audit": audit, "source_details": details}
